/// District suggestions for a state, or empty if absent (use free text).
List<String> districtsForState(String state) {
  final list = kDistrictsByState[state];
  if (list == null) return const [];
  return List<String>.unmodifiable(list);
}

/// True if [state] is a known entry in [kIndianStatesAndUTs].
bool isValidIndianState(String state) =>
    kIndianStatesAndUTs.contains(state.trim());
